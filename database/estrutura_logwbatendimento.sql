BEGIN;

CREATE TABLE IF NOT EXISTS public.wb_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    nivel VARCHAR(20) NOT NULL DEFAULT 'info',
    origem VARCHAR(100) NOT NULL,
    evento VARCHAR(150) NOT NULL,
    mensagem TEXT,

    usuario_sistema_id BIGINT,
    atendimento_id BIGINT,
    correlacao_id VARCHAR(100),

    contexto JSONB NOT NULL DEFAULT '{}'::jsonb,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT ck_wb_logs_nivel
        CHECK (nivel IN (
            'debug',
            'info',
            'warn',
            'error',
            'fatal'
        ))
);

COMMENT ON TABLE public.wb_logs IS
    'Registros técnicos e eventos da aplicação de atendimento WhatsApp';

CREATE INDEX IF NOT EXISTS idx_wb_logs_atendimento
    ON public.wb_logs (atendimento_id)
    WHERE atendimento_id IS NOT NULL;

CREATE INDEX IF NOT EXISTS idx_wb_logs_contexto
    ON public.wb_logs USING GIN (contexto);

CREATE INDEX IF NOT EXISTS idx_wb_logs_correlacao
    ON public.wb_logs (correlacao_id)
    WHERE correlacao_id IS NOT NULL;

CREATE INDEX IF NOT EXISTS idx_wb_logs_criado_em
    ON public.wb_logs (criado_em DESC);

CREATE INDEX IF NOT EXISTS idx_wb_logs_evento_criado_em
    ON public.wb_logs (evento, criado_em DESC);

CREATE INDEX IF NOT EXISTS idx_wb_logs_nivel_criado
    ON public.wb_logs (nivel, criado_em DESC);

CREATE INDEX IF NOT EXISTS idx_wb_logs_origem_evento
    ON public.wb_logs (origem, evento);

CREATE INDEX IF NOT EXISTS idx_wb_logs_usuario
    ON public.wb_logs (usuario_sistema_id)
    WHERE usuario_sistema_id IS NOT NULL;

COMMIT;
