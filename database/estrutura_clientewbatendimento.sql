CREATE TABLE IF NOT EXISTS public.wb_modulos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo VARCHAR(60) NOT NULL UNIQUE,
  nome VARCHAR(120) NOT NULL,
  descricao TEXT,
  ativo BOOLEAN NOT NULL DEFAULT TRUE,
  criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  atualizado_em TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.wb_empresa_modulos (
  empresa_id BIGINT NOT NULL,
  modulo_id BIGINT NOT NULL,
  contratado_em DATE NOT NULL DEFAULT CURRENT_DATE,
  ativo BOOLEAN NOT NULL DEFAULT TRUE,
  criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  PRIMARY KEY (empresa_id, modulo_id),
  CONSTRAINT wb_empresa_modulos_empresa_fk
    FOREIGN KEY (empresa_id) REFERENCES public.wb_empresas(id) ON DELETE CASCADE,
  CONSTRAINT wb_empresa_modulos_modulo_fk
    FOREIGN KEY (modulo_id) REFERENCES public.wb_modulos(id) ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS idx_wb_empresa_modulos_modulo_id
  ON public.wb_empresa_modulos(modulo_id);

