BEGIN;

-- =====================================================
-- EMPRESAS
-- =====================================================

CREATE TABLE IF NOT EXISTS public.wb_empresas (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    cnpj VARCHAR(14) NOT NULL UNIQUE,
    razao_social VARCHAR(255) NOT NULL,
    nome_fantasia VARCHAR(255),
    status VARCHAR(20) NOT NULL DEFAULT 'Ativa'
        CHECK (status IN ('Ativa', 'Inativa')),
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_wb_empresas_status
    ON public.wb_empresas (status);


-- =====================================================
-- CONTATOS DOS CLIENTES
-- =====================================================

CREATE TABLE IF NOT EXISTS public.wb_usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(150),
    telefone VARCHAR(30) NOT NULL UNIQUE,
    whatsapp_id VARCHAR(80),
    empresa_id BIGINT,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_wb_usuarios_empresa
        FOREIGN KEY (empresa_id)
        REFERENCES public.wb_empresas(id)
        ON UPDATE CASCADE
        ON DELETE SET NULL
);

COMMENT ON TABLE public.wb_usuarios IS
    'Contatos de clientes utilizados na integração com o WhatsApp';

COMMENT ON COLUMN public.wb_usuarios.empresa_id IS
    'Referência à empresa cadastrada em wb_empresas';

-- =====================================================
-- ÍNDICES
-- =====================================================

CREATE INDEX IF NOT EXISTS idx_wb_usuarios_empresa_id
    ON public.wb_usuarios (empresa_id);

CREATE INDEX IF NOT EXISTS idx_wb_usuarios_nome
    ON public.wb_usuarios (nome);

CREATE INDEX IF NOT EXISTS idx_wb_usuarios_whatsapp_id
    ON public.wb_usuarios (whatsapp_id);

COMMIT;

