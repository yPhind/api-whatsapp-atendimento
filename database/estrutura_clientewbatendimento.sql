  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'wb_empresas_quantidade_notas_check'
      AND conrelid = 'public.wb_empresas'::regclass
  ) THEN
    ALTER TABLE public.wb_empresas
