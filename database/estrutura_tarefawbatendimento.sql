BEGIN;

CREATE TABLE IF NOT EXISTS public.wb_tarefas (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id INTEGER NOT NULL,
    titulo VARCHAR(64) NOT NULL,
    observacao TEXT NOT NULL,
    data_prevista DATE,
    criado_em TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    atualizado_em TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    status VARCHAR(20) NOT NULL DEFAULT 'em_digitacao',

    CONSTRAINT wb_tarefas_status_check
        CHECK (status IN ('em_digitacao', 'realizada'))
);

CREATE TABLE IF NOT EXISTS public.wb_tarefas_anexos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tarefa_id BIGINT NOT NULL,
    nome_original VARCHAR(255) NOT NULL,
    nome_arquivo VARCHAR(255) NOT NULL,
    mime_type VARCHAR(100) NOT NULL,
    tamanho BIGINT NOT NULL,
    criado_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT wb_tarefas_anexos_nome_arquivo_key
        UNIQUE (nome_arquivo),

    CONSTRAINT wb_tarefas_anexos_mime_type_check
        CHECK (mime_type IN (
            'application/pdf',
            'image/jpeg',
            'image/png'
        )),

    CONSTRAINT wb_tarefas_anexos_tamanho_check
        CHECK (tamanho > 0 AND tamanho <= 52428800),

    CONSTRAINT wb_tarefas_anexos_tarefa_id_fkey
        FOREIGN KEY (tarefa_id)
        REFERENCES public.wb_tarefas(id)
        ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_wb_tarefas_anexos_tarefa
    ON public.wb_tarefas_anexos (tarefa_id);

CREATE INDEX IF NOT EXISTS idx_wb_tarefas_criado_em
    ON public.wb_tarefas (criado_em DESC);

CREATE INDEX IF NOT EXISTS idx_wb_tarefas_status_criado
    ON public.wb_tarefas (usuario_id, status, criado_em DESC);

CREATE INDEX IF NOT EXISTS idx_wb_tarefas_usuario
    ON public.wb_tarefas (usuario_id);

CREATE INDEX IF NOT EXISTS idx_wb_tarefas_usuario_data
    ON public.wb_tarefas (usuario_id, data_prevista, criado_em DESC);

CREATE INDEX IF NOT EXISTS idx_wb_tarefas_usuario_status
    ON public.wb_tarefas (usuario_id, status);

COMMIT;
