-- Estrutura complementar de clientewbatendimento
-- Executar após backup. wb_empresas já existe neste banco.
CREATE TABLE IF NOT EXISTS public.wb_usuarios (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome varchar(150),
  telefone varchar(20) NOT NULL UNIQUE,
  identificacao varchar(100),
  whatsapp_id varchar(100) UNIQUE,
  ativo boolean NOT NULL DEFAULT true,
  criado_em timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
  atualizado_em timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
  empresa_id bigint
);
CREATE INDEX IF NOT EXISTS idx_wb_usuarios_empresa_id ON public.wb_usuarios (empresa_id);
CREATE INDEX IF NOT EXISTS idx_wb_usuarios_nome ON public.wb_usuarios (nome);
