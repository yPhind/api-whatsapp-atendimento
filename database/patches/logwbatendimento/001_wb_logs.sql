-- Novo repositório de logs técnicos para logwbatendimento.
-- O histórico operacional fica em wbatendimento.wb_historico_atendimentos.
CREATE TABLE IF NOT EXISTS public.wb_logs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nivel varchar(20) NOT NULL DEFAULT 'info'
    CHECK (nivel IN ('debug','info','warn','error','fatal')),
  origem varchar(120) NOT NULL,
  evento varchar(120) NOT NULL,
  mensagem text NOT NULL,
  usuario_sistema_id bigint,
  atendimento_id bigint,
  correlacao_id varchar(100),
  contexto jsonb NOT NULL DEFAULT '{}'::jsonb,
  criado_em timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_wb_logs_criado_em ON public.wb_logs (criado_em DESC);
CREATE INDEX IF NOT EXISTS idx_wb_logs_nivel_criado_em ON public.wb_logs (nivel, criado_em DESC);
CREATE INDEX IF NOT EXISTS idx_wb_logs_evento_criado_em ON public.wb_logs (evento, criado_em DESC);
CREATE INDEX IF NOT EXISTS idx_wb_logs_atendimento_id ON public.wb_logs (atendimento_id) WHERE atendimento_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_wb_logs_correlacao_id ON public.wb_logs (correlacao_id) WHERE correlacao_id IS NOT NULL;
