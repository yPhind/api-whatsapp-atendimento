-- 1. Perfis reutilizáveis de permissão
CREATE TABLE IF NOT EXISTS wb_roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(80) NOT NULL UNIQUE,
    descricao VARCHAR(255),
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 2. Catálogo de módulos e ações
CREATE TABLE IF NOT EXISTS wb_permissoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(120) NOT NULL UNIQUE,
    modulo VARCHAR(80) NOT NULL,
    acao VARCHAR(80) NOT NULL,
    descricao VARCHAR(255),
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_wb_permissao_modulo_acao
        UNIQUE (modulo, acao)
);

-- 3. Permissões associadas aos perfis
CREATE TABLE IF NOT EXISTS wb_role_permissoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_id BIGINT NOT NULL
        REFERENCES wb_roles(id) ON DELETE CASCADE,
    permissao_id BIGINT NOT NULL
        REFERENCES wb_permissoes(id) ON DELETE CASCADE,
    permitido BOOLEAN NOT NULL DEFAULT FALSE,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_wb_role_permissao
        UNIQUE (role_id, permissao_id)
);

-- 4. Associação entre usuários e perfis
CREATE TABLE IF NOT EXISTS wb_usuario_roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL
        REFERENCES wb_usuarios_sistema(id) ON DELETE CASCADE,
    role_id BIGINT NOT NULL
        REFERENCES wb_roles(id) ON DELETE CASCADE,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_wb_usuario_role
        UNIQUE (usuario_id, role_id)
);

-- 5. Permissões individuais dos usuários
-- permitido = TRUE: concede acesso
-- permitido = FALSE: bloqueia acesso
CREATE TABLE IF NOT EXISTS wb_usuario_permissoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL
        REFERENCES wb_usuarios_sistema(id) ON DELETE CASCADE,
    permissao_id BIGINT NOT NULL
        REFERENCES wb_permissoes(id) ON DELETE CASCADE,
    permitido BOOLEAN NOT NULL,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_wb_usuario_permissao
        UNIQUE (usuario_id, permissao_id)
);

-- Índices para consultas de autorização
CREATE INDEX IF NOT EXISTS idx_wb_usuario_roles_usuario
    ON wb_usuario_roles(usuario_id);

CREATE INDEX IF NOT EXISTS idx_wb_role_permissoes_role
    ON wb_role_permissoes(role_id);

CREATE INDEX IF NOT EXISTS idx_wb_usuario_permissoes_usuario
    ON wb_usuario_permissoes(usuario_id);

